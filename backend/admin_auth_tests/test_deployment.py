"""Operator workflow on a restored disposable DB; never on an operational DSN."""
import asyncio
import ast
import contextlib
import hashlib
import io
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import psycopg
from admin_auth import AdminAuth, install_admin_auth
from admin_auth_ops import manage
from test_runtime_routes import request


@unittest.skipUnless(os.getenv('ADMIN_AUTH_RESTORED_DATABASE_URL'), 'Restored disposable PostgreSQL required')
class Deployment(unittest.TestCase):
    def test_migration_provision_activation_verifier_and_closed_recovery(self):
        dsn = os.environ['ADMIN_AUTH_RESTORED_DATABASE_URL']
        with psycopg.connect(dsn) as conn:
            if conn.execute('SELECT current_database()').fetchone()[0] != 'restore_fixture':
                raise RuntimeError('Workflow test accepts only disposable restore_fixture')
            before = manage.projection_receipt(conn)
        runtime = Path(os.environ['ADMIN_AUTH_RUNTIME_DIR'])
        sys.path.insert(0,str(runtime))
        from runtime_p11.service import create_app
        from postgres_store import PostgresStore
        from harpia_deterministic.p11 import install_deterministic_harpia
        with tempfile.TemporaryDirectory() as directory:
            base = Path(directory)
            (base/'app.py').write_bytes((runtime/'app.py').read_bytes())
            value = dict(release='workflow-fixture',baseline={'app.py':manage.digest(base/'app.py')})
            saved = base/'.admin-auth-backups'/value['release']
            saved.mkdir(parents=True)
            (saved/'app.original.py').write_bytes((base/'app.py').read_bytes())
            receipt = dict(dump_sha256='fixture-archive-receipt',projection_count=before[0],projection_digest=before[1])
            for name in ['backup.json','restore-verified.json']:
                (saved/name).write_text(json.dumps(receipt))
            with patch.object(manage,'BASE',base),patch.object(manage,'RELEASE',Path(__file__).resolve().parents[1]),contextlib.redirect_stdout(io.StringIO()):
                config={'HARPISENSE_DATABASE_URL':dsn,'HARPISENSE_ADMIN_USER':'technical-fixture','HARPISENSE_ADMIN_PASSWORD':'technical-password'}
                manage.migrate(value,config)
                with patch.object(sys.stdin,'isatty',return_value=True),patch('builtins.input',return_value='fixture-owner'),patch.object(manage.getpass,'getpass',return_value='isolated account password'):
                    manage.provision(config)
                manage.activate(value,config)
                self.assertIn('install_admin_auth', (base/'app.py').read_text())
                # Activate refuses unexpected drift instead of replacing newer files.
                with self.assertRaises(RuntimeError):
                    manage.activate(value,config)
                store=PostgresStore(dsn)
                app=create_app(store,username='technical-fixture',password='technical-password',service_token='technical-token')
                install_deterministic_harpia(app,store)
                install_admin_auth(app,AdminAuth(dsn),allowed_origins=['http://127.0.0.1:4174'])

                def asgi(method,path,*,body=None,token=None,authorization=None):
                    return asyncio.run(request(app,method,path,body=body,
                        authorization=authorization or ('Bearer '+token if token else None),origin='http://127.0.0.1:4174'))

                with patch.object(manage,'http',asgi),patch.object(sys.stdin,'isatty',return_value=True),patch('builtins.input',return_value='fixture-owner'),patch.object(manage.getpass,'getpass',return_value='isolated account password'):
                    manage.verify(value,config)
                result=json.loads((saved/'live-verification.json').read_text())
                self.assertEqual(result['checks']['absolute_expiration_code'],'SESSION_EXPIRED')
                self.assertEqual(result['checks']['idle_expiration_code'],'SESSION_EXPIRED')
                self.assertEqual(result['checks']['logout_replay_refused'],401)
                self.assertNotIn('isolated account password',json.dumps(result))
                with psycopg.connect(dsn) as conn:
                    self.assertEqual(before,manage.projection_receipt(conn))
                    self.assertEqual(conn.execute('SELECT count(*) FROM hs_admin_session WHERE revoked_at IS NULL').fetchone()[0],0)
                # Test the recovery middleware generated by backup, against real routes.
                source=Path(manage.__file__).read_text()
                assignment=next(node for node in ast.walk(ast.parse(source)) if isinstance(node,ast.Assign) and any(isinstance(target,ast.Name) and target.id=='guarded' for target in node.targets))
                guard=ast.literal_eval(assignment.value.right)
                (saved/'app.recovery.py').write_text((saved/'app.original.py').read_text()+guard)
                manage.recover(value)
                app=create_app(store,username='technical-fixture',password='technical-password',service_token='technical-token')
                scope={'app':app}
                exec(compile(guard,'recovery-fixture','exec'),scope)
                self.assertEqual(asgi('GET','/api/v1/p11/telemetry')[0],503)
                self.assertEqual(asgi('POST','/api/v1/p11/ingest/telemetry',body={'id':'fixture','source':'trusted-service','data':{}},authorization='Basic dGVjaG5pY2FsLWZpeHR1cmU6dGVjaG5pY2FsLXBhc3N3b3Jk')[0],403)


if __name__=='__main__':
    unittest.main()
